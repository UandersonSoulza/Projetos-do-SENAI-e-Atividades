    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        try {
    int id = Integer.parseInt(txtId.getText());
    int resposta = javax.swing.JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir este produto?", "Confirmar Exclusão", javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (resposta == javax.swing.JOptionPane.YES_OPTION) {
        boolean sucesso = produtoController.excluirProduto(id);
        if (sucesso) {
            javax.swing.JOptionPane.showMessageDialog(this, "Produto excluído!");
            limparCampos();
            preencherTabela(produtoController.listarProdutos());
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto para excluir!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
}
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        try {
            String nome = txtNome.getText();
            int qtd = Integer.parseInt(txtQuantidade.getText());
            double preco = Double.parseDouble(txtPreco.getText());
            com.mycompany.stockcontrol.model.Categoria categoriaSelecionada = (com.mycompany.stockcontrol.model.Categoria) cbCategoria.getSelectedItem();
            int idCategoria = categoriaSelecionada.getIdCategorias();

            // 👇 Agora enviamos os 4 parâmetros para o Controller!
            boolean sucesso = produtoController.cadastrarProduto(nome, qtd, preco, idCategoria);
            
            if (sucesso) {
                javax.swing.JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
                limparCampos();
                preencherTabela(produtoController.listarProdutos()); // Atualiza a tabela
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao cadastrar. Verifique os dados.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException ex) {
           
            javax.swing.JOptionPane.showMessageDialog(this, "Quantidade, Preço e Categoria devem ser numéricos!", "Erro de Validação", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        try {
        int id = Integer.parseInt(txtId.getText());
        String nome = txtNome.getText();
        int qtd = Integer.parseInt(txtQuantidade.getText());
        double preco = Double.parseDouble(txtPreco.getText());

        // 👇 1. PEGA A CATEGORIA QUE ESTÁ SELECIONADA NO COMBOBOX
        com.mycompany.stockcontrol.model.Categoria categoriaSelecionada = (com.mycompany.stockcontrol.model.Categoria) cbCategoria.getSelectedItem();
        
        // Proteção para o caso de tentar salvar sem nenhuma categoria selecionada
        if (categoriaSelecionada == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecione uma categoria!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int idCategoria = categoriaSelecionada.getIdCategorias();

        // 👇 2. ALTERADO: Agora envia também o 'idCategoria' para o controller
        boolean sucesso = produtoController.atualizarProduto(id, nome, qtd, preco, idCategoria);
        
        if (sucesso) {
            javax.swing.JOptionPane.showMessageDialog(this, "Produto atualizado com sucesso!");
            limparCampos();
            preencherTabela(produtoController.listarProdutos());
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao atualizar.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto válido e preencha os campos!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_btnEditarActionPerformed

