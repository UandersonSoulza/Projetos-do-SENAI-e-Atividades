    private void tabelaProdutosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaProdutosMouseClicked
       int linhaSelecionada = tabelaProdutos.getSelectedRow();
    if (linhaSelecionada != -1) {
        txtId.setText(tabelaProdutos.getValueAt(linhaSelecionada, 0).toString());
        txtNome.setText(tabelaProdutos.getValueAt(linhaSelecionada, 1).toString());
        txtQuantidade.setText(tabelaProdutos.getValueAt(linhaSelecionada, 2).toString());
        txtPreco.setText(tabelaProdutos.getValueAt(linhaSelecionada, 3).toString());
        
       
        if (tabelaProdutos.getValueAt(linhaSelecionada, 4) != null) {
            String nomeCategoriaTab = tabelaProdutos.getValueAt(linhaSelecionada, 4).toString();
            
            for (int i = 0; i < cbCategoria.getItemCount(); i++) {
                com.mycompany.stockcontrol.model.Categoria c = (com.mycompany.stockcontrol.model.Categoria) cbCategoria.getItemAt(i);
                if (c != null && c.getNomeCategoria().equals(nomeCategoriaTab)) {
                    cbCategoria.setSelectedIndex(i);
                    break;
                }
            }
        }
    }
    }//GEN-LAST:event_tabelaProdutosMouseClicked

