// Método para limpar os campos de texto após cadastrar ou atualizar
private void limparCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtQuantidade.setText("");
        txtPreco.setText("");
        if (cbCategoria.getItemCount() > 0) {
            cbCategoria.setSelectedIndex(-1); 
        }
    }

// Método para preencher a JTable com os dados do banco
private void preencherTabela(java.util.List<com.mycompany.stockcontrol.model.Produto> lista) {
   javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tabelaProdutos.getModel();
    modelo.setRowCount(0); // Limpa a tabela antes de preencher
    
    for (com.mycompany.stockcontrol.model.Produto p : lista) {
        
        //Pega o getNomeCategoria()
        String categoriaDisplay = (p.getCategoria() != null && p.getCategoria().getNomeCategoria() != null) 
                ? p.getCategoria().getNomeCategoria() 
                : "Sem Categoria";
        
        modelo.addRow(new Object[]{
            p.getIdProduto(),
            p.getNome(),
            p.getQuantidade(),
            p.getPreco(),
            categoriaDisplay, 
            p.getUsuario().getLogin() 
        });
    }
}

private void preencherComboCategorias() {
        cbCategoria.removeAllItems(); 
        java.util.List<com.mycompany.stockcontrol.model.Categoria> lista = categoriaController.listarCategorias();
        for (com.mycompany.stockcontrol.model.Categoria c : lista) {
            // Tem de ir nas propriedades do ComboBox no Design -> Code -> Type Parameters e deixar vazio ou colocar <Object>
            // Adiciona o objeto inteiro ao invés de apenas a String
            cbCategoria.addItem(c); 
        }
    }
